#!/usr/bin/env python3
"""Read-only documentation checker for the auto-the-spire docs corpus.

Checks, per Markdown file:
  1. every relative link target resolves to an existing file;
  2. every '#anchor' resolves to a heading slug generated by the same rules GitHub uses;
  3. every ```json fenced block parses as strict JSON (no duplicate keys);
  4. fenced code blocks are balanced;
  5. no trailing whitespace on code/text lines;
  6. requirement IDs (AI-/NET-) declared in a spec appear in the verification matrix.

Usage:  python tools/doc-check/check_docs.py [root]
Exit code is the number of failed checks (0 = clean).
"""

from __future__ import annotations

import json
import re
import sys
import unicodedata
from pathlib import Path

FENCE_RE = re.compile(r"^\s*(```+|~~~+)(.*)$")
LINK_RE = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
REQ_DEF_RE = re.compile(r"^\|\s*(AI-\d+|NET-\d+)\s*\|", re.M)
REQ_USE_RE = re.compile(r"\b(AI-\d+|NET-\d+)\b")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*$")

SKIP_DIRS = {".git", "bin", "obj", "node_modules",
             # third-party / vendored trees outside the project documentation corpus
             "reference", "tools", "sts2", "archive", "fmod-gdextension", ".agents", ".specify"}


def slugify(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\*\*([^*]*)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]*)\*", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.strip().lower()
    out = []
    for ch in text:
        if ch in "-_":
            out.append(ch)
        elif ch.isspace():
            out.append("-")
        elif unicodedata.category(ch)[0] in {"L", "N"}:
            out.append(ch)
    return "".join(out)


def headings(text: str) -> set[str]:
    seen: dict[str, int] = {}
    result: set[str] = set()
    in_fence = False
    for line in text.splitlines():
        m = FENCE_RE.match(line)
        if m:
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        h = HEADING_RE.match(line)
        if not h:
            continue
        base = slugify(h.group(2))
        n = seen.get(base, 0)
        seen[base] = n + 1
        result.add(base if n == 0 else f"{base}-{n}")
    return result


def iter_docs(root: Path):
    for path in sorted(root.rglob("*.md")):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        yield path


def check_file(path: Path, root: Path, failures: list[str]) -> None:
    rel = path.relative_to(root).as_posix()
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()

    # 2/4: fences and trailing whitespace
    depth = 0
    json_blocks: list[tuple[int, str]] = []
    current: list[str] | None = None
    current_line = 0
    for i, line in enumerate(lines, start=1):
        m = FENCE_RE.match(line)
        if m:
            if depth == 0:
                depth = 1
                info = m.group(2).strip().lower()
                if info.startswith("json"):
                    current, current_line = [], i
            else:
                depth = 0
                if current is not None:
                    json_blocks.append((current_line, "\n".join(current)))
                current = None
            continue
        if current is not None:
            current.append(line)
        if line != line.rstrip():
            failures.append(f"{rel}:{i}: trailing whitespace")
    if depth != 0:
        failures.append(f"{rel}: unbalanced code fence")

    # 3: JSON blocks
    for lineno, block in json_blocks:
        try:
            json.loads(block, object_pairs_hook=_no_dup_keys)
        except Exception as exc:  # noqa: BLE001 - report any parse problem
            failures.append(f"{rel}:{lineno}: invalid JSON block: {exc}")

    # 1/2: links
    anchor_cache: dict[Path, set[str]] = {}
    for i, line in enumerate(lines, start=1):
        for _, target in LINK_RE.findall(line):
            if target.startswith(("http://", "https://", "mailto:")):
                continue
            file_part, _, anchor = target.partition("#")
            if not file_part:
                dest = path
            else:
                dest = (path.parent / file_part).resolve()
            if not dest.exists():
                failures.append(f"{rel}:{i}: missing link target '{target}'")
                continue
            if anchor and dest.suffix == ".md":
                cached = anchor_cache.get(dest)
                if cached is None:
                    cached = headings(dest.read_text(encoding="utf-8"))
                    anchor_cache[dest] = cached
                if anchor not in cached:
                    failures.append(f"{rel}:{i}: missing anchor '{target}'")


def _no_dup_keys(pairs):
    seen = {}
    for key, value in pairs:
        if key in seen:
            raise ValueError(f"duplicate JSON key {key!r}")
        seen[key] = value
    return seen


def check_traceability(root: Path, failures: list[str]) -> None:
    spec = root / "docs/design"
    declared: list[str] = []
    for name in ("ai-the-spire/spec.md", "net-the-spire/spec.md"):
        declared += REQ_DEF_RE.findall((spec / name).read_text(encoding="utf-8"))
    declared = sorted(set(declared))

    matrix_paths = [
        root / "docs/design/ai-net-verification.md",
        root / "docs/design/ai-net-implementation-plan.md",
    ]
    used = set()
    for path in matrix_paths:
        used |= set(REQ_USE_RE.findall(path.read_text(encoding="utf-8")))

    for req in declared:
        if req not in used:
            failures.append(f"docs/design: requirement {req} has no verification/plan reference")
    for req in sorted(used - set(declared)):
        failures.append(f"docs/design: reference to undeclared requirement {req}")
    print(f"requirements declared: {len(declared)} -> {', '.join(declared)}")


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    failures: list[str] = []
    docs = list(iter_docs(root))
    for path in docs:
        check_file(path, root, failures)
    check_traceability(root, failures)
    print(f"scanned {len(docs)} Markdown files")
    for failure in failures:
        print("FAIL:", failure)
    print(f"{len(failures)} problem(s)")
    return min(len(failures), 255)


if __name__ == "__main__":
    sys.exit(main())
