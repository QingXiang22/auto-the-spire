<#
.SYNOPSIS
    Decompile reference/orimod/OriMod.dll back into a browsable, buildable C# project.

.DESCRIPTION
    Runs ILSpy over the target mod assembly with the shipped game runtime plus the
    declared BaseLib dependency as reference paths, then rewrites the generated
    .csproj so it builds on this machine (see the notes inside the generated file).

    Why a manually extracted nupkg instead of `dotnet tool install`: ilspycmd 11.x
    ships a net10.0 tool package, and the installed .NET SDK (9.0.x) refuses it with
    "DotnetToolSettings.xml not found in package". The .NET 10 runtime is present, so
    the extracted tool DLL is invoked with `dotnet <ilspycmd.dll>`.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools/orimod-decompile/decompile.ps1
    powershell -ExecutionPolicy Bypass -File tools/orimod-decompile/decompile.ps1 -GameDir "D:\Steam\steamapps\common\Slay the Spire 2"
#>

param(
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path,
    [string]$OutDir = "reference\orimod\src",
    [string]$GameDir = "E:\Steam\steamapps\common\Slay the Spire 2",
    [string]$BaseLibDir = "E:\Steam\steamapps\workshop\content\2868840\3737335127\BaseLib"
)

$ErrorActionPreference = "Stop"

$toolVersion = "11.1.0.9782"
$toolDir = Join-Path $PSScriptRoot "nuget"
$toolDll = Join-Path $toolDir "pkg\tools\net10.0\any\ilspycmd.dll"
$nupkg = Join-Path $toolDir "ilspycmd.nupkg"

if (-not (Test-Path $toolDll)) {
    New-Item -ItemType Directory -Force -Path $toolDir | Out-Null
    $url = "https://api.nuget.org/v3-flatcontainer/ilspycmd/$toolVersion/ilspycmd.$toolVersion.nupkg"
    Write-Host "downloading $url"
    Invoke-WebRequest -Uri $url -OutFile $nupkg -UseBasicParsing
    Copy-Item $nupkg (Join-Path $toolDir "ilspycmd.zip") -Force
    Expand-Archive (Join-Path $toolDir "ilspycmd.zip") -DestinationPath (Join-Path $toolDir "pkg") -Force
}

# Reference assemblies: the shipped game runtime (GodotSharp, sts2, 0Harmony) plus
# BaseLib, whose version the mod manifest pins at min_version 3.4.7.
$gameRuntime = Join-Path $GameDir "data_sts2_windows_x86_64"
$inputDll = Join-Path $Root "reference\orimod\OriMod.dll"
$out = Join-Path $Root $OutDir

if (-not (Test-Path $inputDll)) { throw "target assembly not found: $inputDll" }
if (-not (Test-Path (Join-Path $gameRuntime "sts2.dll"))) { throw "game runtime not found: $gameRuntime" }
if (-not (Test-Path (Join-Path $BaseLibDir "BaseLib.dll"))) { throw "BaseLib not found: $BaseLibDir" }

if (Test-Path $out) { Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory -Force -Path $out | Out-Null

dotnet $toolDll --disable-updatecheck -p -o $out --nested-directories `
    -r $gameRuntime -r $BaseLibDir $inputDll
if ($LASTEXITCODE -ne 0) { throw "ilspycmd failed with exit code $LASTEXITCODE" }

# ILSpy emits LangVersion 14.0 (needs a .NET 10 SDK) and absolute HintPaths.
$csproj = @"
<Project Sdk="Microsoft.NET.Sdk">
  <!--
    Generated by tools/orimod-decompile/decompile.ps1 (ILSpy $toolVersion) from
    reference/orimod/OriMod.dll, then adjusted by that script:
      * LangVersion 14.0 -> latest (the local .NET 9 SDK cannot parse "14.0")
      * HintPath roots hoisted into overridable properties
      * Nullable=annotations, matching the annotations the original assembly carries
    Build it to check that the recovered source is faithful; the real mod loads
    from <game>\mds\OriMod\OriMod.dll, not from this project.
  -->
  <PropertyGroup>
    <AssemblyName>OriMod</AssemblyName>
    <GenerateAssemblyInfo>False</GenerateAssemblyInfo>
    <TargetFramework>net9.0</TargetFramework>
  </PropertyGroup>
  <PropertyGroup>
    <LangVersion>latest</LangVersion>
    <AllowUnsafeBlocks>True</AllowUnsafeBlocks>
    <CheckForOverflowUnderflow>False</CheckForOverflowUnderflow>
    <Nullable>annotations</Nullable>
  </PropertyGroup>
  <PropertyGroup>
    <!-- Override on the command line, e.g. -p:GameDir=D:\Steam\...\Slay the Spire 2 -->
    <GameDir Condition="'`$(GameDir)' == ''">$GameDir</GameDir>
    <GameRuntimeDir Condition="'`$(GameRuntimeDir)' == ''">`$(GameDir)\data_sts2_windows_x86_64</GameRuntimeDir>
    <BaseLibDir Condition="'`$(BaseLibDir)' == ''">$BaseLibDir</BaseLibDir>
  </PropertyGroup>
  <ItemGroup>
    <Reference Include="GodotSharp">
      <HintPath>`$(GameRuntimeDir)\GodotSharp.dll</HintPath>
    </Reference>
    <Reference Include="sts2">
      <HintPath>`$(GameRuntimeDir)\sts2.dll</HintPath>
    </Reference>
    <Reference Include="0Harmony">
      <HintPath>`$(GameRuntimeDir)\0Harmony.dll</HintPath>
    </Reference>
    <Reference Include="BaseLib">
      <HintPath>`$(BaseLibDir)\BaseLib.dll</HintPath>
    </Reference>
  </ItemGroup>
</Project>
"@
Set-Content -Path (Join-Path $out "OriMod.csproj") -Value $csproj -Encoding utf8

$cs = Get-ChildItem $out -Recurse -Filter *.cs
Write-Host "decompiled $($cs.Count) .cs files to $out"
