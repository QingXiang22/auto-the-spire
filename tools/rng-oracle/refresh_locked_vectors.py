"""Regenerate current-source vectors without reading any production results."""
import argparse
import importlib
import json
import subprocess
from pathlib import Path
from locked_rng_oracle import ROOT, reference_lock, hash64, deterministic_hash_code
from normal_opening_vectors import write_definitions, write_neow_pool

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / '.artifacts/rng-vectors')
    args = parser.parse_args()
    reference_lock()
    output = args.output.resolve()
    subprocess.run(['dotnet', 'run', '--project', str(ROOT / 'tools/rng-oracle/reference-vectors'), '-c', 'Release', '--', str(ROOT), str(output)], check=True)
    fixtures = ROOT / 'tools/base-spire-dev/fixtures'
    def read(name): return json.loads((output / name).read_text(encoding='utf-8'))
    def write(path, data): path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    metadata = read('metadata.json')
    write(fixtures / 'reference-pool-metadata.json', metadata)
    opening = read('normal-opening-vectors.json')
    opening['neow_pool'] = {kind: [r['id'] for r in metadata['neow'][kind] if r['name'] != 'MassiveScroll'] for kind in ['curse', 'positive']}
    write(fixtures / 'normal-opening-vectors.json', opening)
    for name in ['act-one-map-vectors.json', 'map-gaussian-vectors.json', 'normal-combat-vectors.json', 'slimes-vectors.json', 'ironclad-source-metadata.json', 'normal-unknown-room-vector.json', 'normal-event-selection-vector.json']:
        write(fixtures / name, read(name))
    base = ROOT / 'mod-the-spire/base-spire/run'
    write_definitions(opening, base / 'opening-source.spire')
    write_neow_pool(opening, base / 'neow-pool.spire')
    for module, name in [('dsl_rng_vectors', 'source-rng-vectors.json'), ('normal_reward_vectors', 'normal-reward-vectors.json'), ('enemy_move_vectors', 'enemy-move-vectors.json'), ('pickup_upgrade_vectors', 'pickup-upgrade-vectors.json')]:
        write(fixtures / name, importlib.import_module(module).generate())
    vectors = read('word64-vectors.json')['vectors']
    for row in vectors:
        assert hash64(row['seed']) == row['hash'], row
        assert deterministic_hash_code(row['seed']) == row['root'], row
    lines = ['// Generated by tools/rng-oracle/refresh_locked_vectors.py from the locked native reference.',
             'namespace CoreTheSpire.Engine.Tests;', 'internal static class Word64Vectors', '{',
             '    internal static readonly (string Text, ulong Hash)[] All = [']
    lines += ['        (' + json.dumps(row['seed'], ensure_ascii=True) + ', ' + str(row['hash']) + 'UL),' for row in vectors]
    lines += ['    ];', '}']
    (ROOT / 'core-the-spire/Core.TheSpire.Engine.Tests/Word64Vectors.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Locked native vectors, independent consumer vectors and DSL pool declarations refreshed.')

if __name__ == '__main__': main()
