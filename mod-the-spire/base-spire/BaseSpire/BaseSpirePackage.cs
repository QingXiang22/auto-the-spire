public sealed class BaseSpirePackage(bool deadlyEnemies = false, bool toughEnemies = false) : IRulePackage
{
    public PackageInfo Info { get; } = new("base-spire", "0.1.0");

    public void Register(ContentRegistry registry)
    {
        foreach (var stateVariable in BaseSpireContent.LoadStateDefinitions()) registry.Register(stateVariable);
        registry.Register(new RelicDefinition(BaseSpireIds.BurningBlood, RunRelicRarity.Starter, InSharedPool: false));
        registry.Register(new RelicDefinition(BaseSpireIds.Anchor, RunRelicRarity.Common));
        registry.Register(new RelicDefinition(BaseSpireIds.Vajra, RunRelicRarity.Common));
        registry.Register(new RelicDefinition(BaseSpireIds.PotionBelt, RunRelicRarity.Common));
        registry.Register(new RelicDefinition(BaseSpireIds.CharonsAshes, RunRelicRarity.Rare,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.SelfFormingClay, RunRelicRarity.Uncommon,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.RedSkull, RunRelicRarity.Common,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.DemonTongue, RunRelicRarity.Rare,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.PaperPhrog, RunRelicRarity.Uncommon,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.RuinedHelmet, RunRelicRarity.Rare,
            InSharedPool: false, CharacterPoolIds: [BaseSpireIds.Ironclad]));
        registry.Register(new RelicDefinition(BaseSpireIds.Circlet, RunRelicRarity.None,
            InSharedPool: false, IsFallback: true, IsStackable: true));
        foreach (var potion in BaseSpireContent.LoadPotions()) registry.Register(potion);
        registry.Register(BaseSpireContent.Ironclad());
        registry.Register(new PowerDefinition(BaseSpireIds.Strength, Role: PowerRole.Strength));
        registry.Register(new PowerDefinition(BaseSpireIds.DemonFormPower, PowerTrigger.AfterPlayerTurnStart,
            BaseSpireIds.Strength));
        registry.Register(new PowerDefinition(BaseSpireIds.NoDrawPower, PowerTrigger.AfterPlayerTurnEnd,
            Role: PowerRole.NoDraw, DecrementOnTrigger: true));
        registry.Register(new PowerDefinition(BaseSpireIds.SelfFormingClayPower, PowerTrigger.AfterPlayerTurnStart,
            TriggerRuleEffect: new SequenceEffect([
                new GainBlockEffect(3, BaseSpireIds.SelfFormingClayPower),
                new RemovePowerEffect(BaseSpireIds.SelfFormingClayPower)
            ])));
        foreach (var power in BaseSpireContent.LoadIroncladPowers()) registry.Register(power);
        foreach (var power in BaseSpireContent.LoadPotionPowers()) registry.Register(power);
        registry.Register(new PowerDefinition(BaseSpireIds.WellLaidPlansPower));
        registry.Register(new WellLaidPlansHook());
        registry.Register(new PowerDefinition(BaseSpireIds.BarricadePower));
        registry.Register(new BarricadeHook());
        var enemyContent = BaseSpireContent.LoadEnemyBehavior(new ContentVariantProfile(deadlyEnemies, toughEnemies));
        foreach (var power in enemyContent.Powers) registry.Register(power);
        foreach (var enemy in enemyContent.Enemies) registry.Register(enemy);
        registry.Register(new PowerDefinition(BaseSpireIds.Vulnerable, PowerTrigger.AfterEnemyTurnEnd,
            Role: PowerRole.Vulnerable, DecrementOnTrigger: true, SkipFirstTriggerWhenAppliedToPlayer: true));
        registry.Register(new PowerDefinition(BaseSpireIds.Weak, PowerTrigger.AfterEnemyTurnEnd,
            DecrementOnTrigger: true, SkipFirstTriggerWhenAppliedToPlayer: true, OutgoingDamageMultiplier: 0.75m));
        registry.Register(new PowerDefinition(BaseSpireIds.Shrink,
            OutgoingDamageMultiplier: 0.7m, RemoveWhenApplierDies: true));

        var ironcladCards = BaseSpireContent.LoadIroncladCards();
        foreach (var card in ironcladCards) registry.Register(card);
        IroncladCardPool.Register(registry);
        registry.Register(new CardDefinition(BaseSpireIds.WellLaidPlans, 1, CardType.Power,
            new ApplyPowerEffect(BaseSpireIds.WellLaidPlansPower, 1), Target: TargetSelector.Self,
            Rarity: CardRarity.Uncommon,
            UpgradedEffect: new ApplyPowerEffect(BaseSpireIds.WellLaidPlansPower, 2)));
        registry.Register(new CardDefinition(BaseSpireIds.Dazed, 0, CardType.Status,
            new SequenceEffect(Array.Empty<EffectNode>()), Target: TargetSelector.Self,
            Rarity: CardRarity.Status, Keywords: CardKeywords.Ethereal | CardKeywords.Unplayable));

        foreach (var encounter in BaseSpireContent.LoadEncounters("base-spire.encounters.json"))
            registry.Register(encounter);

        registry.Register(new BurningBloodRunHook());
        registry.Register(new AnchorRunHook());
        registry.Register(new VajraRunHook());
        registry.Register(new PotionBeltRunHook());
        registry.Register(new CharonsAshesHook());
        registry.Register(new SelfFormingClayHook());
        registry.Register(new RedSkullHook());
        registry.Register(new DemonTongueHook());
        registry.Register(new PaperPhrogHook());
        registry.Register(new RuinedHelmetHook());
        registry.Register(BaseSpireMapGenerator.CreateStandardRun());
    }

}

internal sealed class BurningBloodRunHook : IRunHook
