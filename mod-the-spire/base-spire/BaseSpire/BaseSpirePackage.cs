public static class BaseSpireContent
{
    public const int IroncladStartingMaxHp = 80;
    public const int IroncladStartingGold = 99;
    public static IReadOnlyList<ContentId> IroncladStarterDeck() =>
        [.. Enumerable.Repeat(BaseSpireIds.StrikeIronclad, 5), .. Enumerable.Repeat(BaseSpireIds.DefendIronclad, 4), BaseSpireIds.Bash];
    public static CharacterDefinition Ironclad() => new(BaseSpireIds.Ironclad, IroncladStartingMaxHp,
        IroncladStartingGold, IroncladStarterDeck(), [BaseSpireIds.BurningBlood],
        cardPools: [BaseSpireIds.IroncladCardPool]);

    public static IReadOnlyList<CardDefinition> LoadIroncladCards()
    {
        const string resourceName = "BaseSpire.ContentSource.ironclad-cards.spire";
        using var stream = typeof(BaseSpireContent).Assembly.GetManifestResourceStream(resourceName)
            ?? throw new InvalidOperationException($"Missing base-spire content resource '{resourceName}'.");
        using var reader = new System.IO.StreamReader(stream);
        var package = DslSourceParser.Parse(reader.ReadToEnd(), "base-spire/ironclad-cards.spire");
        return SpireCombatDslCompiler.CompileCards(package);
    }

    public static SpireCombatBehaviorContent LoadEnemyBehavior(ContentVariantProfile profile = default)
    {
        const string resourceName = "BaseSpire.ContentSource.enemies.spire";
        using var stream = typeof(BaseSpireContent).Assembly.GetManifestResourceStream(resourceName)
            ?? throw new InvalidOperationException($"Missing base-spire content resource '{resourceName}'.");
        using var reader = new System.IO.StreamReader(stream);
        var package = DslSourceParser.Parse(reader.ReadToEnd(), "base-spire/enemies.spire");
        return SpireCombatBehaviorDslCompiler.Compile(package, profile);
    }

    public static IReadOnlyList<PowerDefinition> LoadIroncladPowers()
    {
        const string resourceName = "BaseSpire.ContentSource.ironclad-powers.spire";
        using var stream = typeof(BaseSpireContent).Assembly.GetManifestResourceStream(resourceName)
