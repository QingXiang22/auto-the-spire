        && context.IsAliveCreature(gameEvent.Target)
        && context.HasRelic(BaseSpireIds.SelfFormingClay)
            ? new GameEventEffect(new ApplyPowerEffect(BaseSpireIds.SelfFormingClayPower, 3), GameEventActor.Target)
            : null;
}

internal sealed class RedSkullHook : IRuleHook
{
    private const string StrengthActiveKey = "red-skull-strength-active";

    public ContentId Id { get; } = ContentId.Parse("base-spire:red-skull-hook");
    public void OnEvent(RuleHookContext context, GameEvent gameEvent) { }

    public GameEventEffect? OnEventEffect(RuleHookContext context, GameEvent gameEvent)
    {
        if (!context.HasRelic(BaseSpireIds.RedSkull)) return null;
        var isHpChange = gameEvent.Type is "damage" or "hp_loss" or "heal";
        if (gameEvent.Type != "combat_started"
            && (!isHpChange || !context.IsPlayerCreature(gameEvent.Target))) return null;

        var active = context.GetInt(StrengthActiveKey) != 0;
        var shouldBeActive = context.PlayerHp * 2 <= context.PlayerMaxHp;
        if (active == shouldBeActive) return null;
        context.SetInt(StrengthActiveKey, shouldBeActive ? 1 : 0);
        return new GameEventEffect(
            new ApplyPowerEffect(BaseSpireIds.Strength, shouldBeActive ? 3 : -3), GameEventActor.Player);
    }
}

internal sealed class DemonTongueHook : IRuleHook
{
    private const string LastTriggeredTurnKey = "demon-tongue-last-triggered-turn";

    public ContentId Id { get; } = ContentId.Parse("base-spire:demon-tongue-hook");
    public void OnEvent(RuleHookContext context, GameEvent gameEvent) { }

    public GameEventEffect? OnEventEffect(RuleHookContext context, GameEvent gameEvent)
    {
        if (gameEvent.Type != "damage" || gameEvent.Amount <= 0
            || !context.IsPlayerCreature(gameEvent.Target)
            || !context.IsPlayerTurn
            || !context.HasRelic(BaseSpireIds.DemonTongue)) return null;
        if (context.GetInt(LastTriggeredTurnKey) == context.Turn) return null;

        context.SetInt(LastTriggeredTurnKey, context.Turn);
        return new GameEventEffect(new HealEffect(gameEvent.Amount), GameEventActor.Target);
    }
}

internal sealed class PaperPhrogHook : IRuleHook
{
    public ContentId Id { get; } = ContentId.Parse("base-spire:paper-phrog-hook");
    public void OnEvent(RuleHookContext context, GameEvent gameEvent) { }

    public decimal ModifyVulnerableMultiplier(RuleHookContext context, string dealerId, string targetId,
        DamageProperties properties, decimal currentMultiplier) =>
        context.HasRelic(BaseSpireIds.PaperPhrog)
        && context.IsPlayerCreature(dealerId)
        && !context.IsPlayerCreature(targetId)
        && (properties & DamageProperties.Move) != 0
        && (properties & DamageProperties.Unpowered) == 0
            ? currentMultiplier + 0.25m
            : currentMultiplier;
}

internal sealed class RuinedHelmetHook : IRuleHook
{
    private const string UsedThisCombatKey = "ruined-helmet-used-this-combat";

    public ContentId Id { get; } = ContentId.Parse("base-spire:ruined-helmet-hook");
    public void OnEvent(RuleHookContext context, GameEvent gameEvent) { }

    public int ModifyPowerAmountReceived(RuleHookContext context, ContentId powerId, PowerRole powerRole,
        string targetId, string applierId, int amount)
    {
        if (amount <= 0 || powerRole != PowerRole.Strength
            || !context.IsPlayerCreature(targetId)
            || !context.HasRelic(BaseSpireIds.RuinedHelmet)
            || context.GetInt(UsedThisCombatKey) != 0) return amount;

        context.SetInt(UsedThisCombatKey, 1);
        return amount * 2;
    }
}

